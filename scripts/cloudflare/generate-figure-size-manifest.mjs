import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const projectRoot = path.resolve(import.meta.dirname, "../..");
const publicRoot = path.join(projectRoot, "public");
const questionBankRoot = path.join(publicRoot, "question-bank");
const outputPath = path.join(
  projectRoot,
  "lib/pastExam/figureSizeManifest.generated.ts",
);
const pngSignature = "89504e470d0a1a0a";

async function findPngFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await findPngFiles(entryPath)));
    } else if (entry.isFile() && entry.name.toLowerCase().endsWith(".png")) {
      files.push(entryPath);
    }
  }

  return files;
}

function toPublicUrl(filePath) {
  const relativePath = path.relative(publicRoot, filePath);
  if (
    relativePath === ".." ||
    relativePath.startsWith(`..${path.sep}`) ||
    path.isAbsolute(relativePath)
  ) {
    throw new Error(`Refusing path outside public/: ${filePath}`);
  }

  return `/${relativePath.split(path.sep).join("/")}`;
}

async function readPngSize(filePath) {
  const buffer = await readFile(filePath);
  if (buffer.length < 24 || buffer.toString("hex", 0, 8) !== pngSignature) {
    throw new Error(`Invalid PNG signature: ${filePath}`);
  }
  if (buffer.readUInt32BE(8) !== 13 || buffer.toString("ascii", 12, 16) !== "IHDR") {
    throw new Error(`Invalid PNG IHDR: ${filePath}`);
  }

  const width = buffer.readUInt32BE(16);
  const height = buffer.readUInt32BE(20);
  if (!Number.isInteger(width) || !Number.isInteger(height) || width <= 0 || height <= 0) {
    throw new Error(`Invalid PNG dimensions: ${filePath}`);
  }

  return { width, height };
}

const files = (await findPngFiles(questionBankRoot)).sort((left, right) =>
  toPublicUrl(left).localeCompare(toPublicUrl(right), "en"),
);
const entries = await Promise.all(
  files.map(async (filePath) => [toPublicUrl(filePath), await readPngSize(filePath)]),
);

const lines = [
  "// Generated by scripts/cloudflare/generate-figure-size-manifest.mjs.",
  "// Do not edit by hand.",
  "export const PAST_EXAM_FIGURE_SIZES: Readonly<",
  "  Record<string, { width: number; height: number }>",
  "> = {",
  ...entries.map(
    ([url, size]) =>
      `  ${JSON.stringify(url)}: { width: ${size.width}, height: ${size.height} },`,
  ),
  "};",
  "",
];

await writeFile(outputPath, lines.join("\n"), "utf8");
console.log(`Generated ${entries.length} figure sizes in ${path.relative(projectRoot, outputPath)}`);
