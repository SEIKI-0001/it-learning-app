/** 類似度の帯。数値そのものではなく、この帯で公開可否を判断する。 */
export type SimilarityBand = "exact_duplicate" | "block" | "review_required" | "notice" | "ok";

/**
 * 類似度スコアの境界（以上で該当）。
 *
 * 根拠:
 *   0.92 … 文字bi-gram Dice でここまで一致すると、語順の入れ替えや語尾の差でしかない。
 *   0.80 … 骨格が同じで数値・固有名詞だけ差し替えた問題がこの帯に入る。人が見る。
 *   0.70 … 同じ論点を別angleから問うている程度。報告のみ。
 */
export const SIMILARITY_THRESHOLDS = {
  block: 0.92,
  reviewRequired: 0.8,
  notice: 0.7,
} as const;

/**
 * 類似度判定を有効にする正規化後の最小文字数。
 *
 * 短文は共通する文字の割合が偶然高くなる（「aとbの組合せ」同士など）。
 * これを下回る問題は notice までに丸め、block / review_required に上げない。
 */
export const SIMILARITY_MIN_PROMPT_LENGTH = 24;

/** 完全一致（exact_duplicate）を主張するのに必要な正規化後の最小文字数。 */
export const SIMILARITY_MIN_EXACT_LENGTH = 16;

/** 文字 n-gram の n。日本語は分かち書きしないため文字単位で取る。 */
export const SIMILARITY_NGRAM_SIZE = 2;

// ---------------------------------------------------------------------------
// 品質ゲート
// ---------------------------------------------------------------------------

export const QUALITY_THRESHOLDS = {
  /**
   * 選択肢どうしが「ほぼ同義」とみなす Dice スコア。
   * 20文字程度の選択肢で末尾の動詞だけが違う（「導入する」/「整備する」）と 0.84 前後になる。
   * そこを拾いたいので 0.82 に置く。
   */
  choiceNearDuplicate: 0.82,
  /**
   * 正答だけ長さが突出しているとみなす倍率。
   * 正答が最長の誤答の 1.6 倍を超えると、長さだけで正解が当てられる。
   */
  correctChoiceLongRatio: 1.6,
  /**
   * 倍率に加えて要求する絶対差（文字）。
   * "意匠権"(3) と "パブリシティ権"(7) は倍率 2.3 を超えるが、
   * 用語を並べただけの選択肢で「長い方が正解」とは言えないため。
   */
  correctChoiceLongMinDiff: 8,
  /** 逆に正答だけ極端に短い場合。 */
  correctChoiceShortRatio: 0.5,
  /** 長さ比較を行う最小文字数（1〜2文字の選択肢で倍率を語らない）。 */
  choiceLengthMinChars: 6,
  /** 問題文が正答本文をそのまま含むとみなす最小文字数。 */
  answerLeakMinChars: 6,
} as const;
