// ============================================================================
// 類似度検査のためのテキスト正規化。
// ----------------------------------------------------------------------------
// 目的は「表記のゆれで別問題に見えてしまう」のを防ぐこと。逆に、正規化しすぎて
// 別の問題どうしが同じ文字列になるのも困るので、落とすのは表記の差だけにする。
//
// 決定的であること（同じ入力なら常に同じ出力）が前提。外部辞書・乱数・時刻を使わない。
//
// 日本語に対する注意:
//   - 英語向けの語幹処理（stemming）は行わない。"データ" を "データ" 以外に潰す処理も
//     入れない。日本語は語尾を機械的に削ると意味が変わるため、壊すより残す。
//   - 分かち書きをしないので、比較は文字 n-gram で行う（similarity.ts）。
//     そのため空白は「区切り」ではなく単なる表記ゆれとして全部落とす。
// ============================================================================

/**
 * 選択肢の先頭に付く「記号」だけを落とす。
 *
 * ここは意図的に厳しくしてある。過去に緩い判定（先頭の英数字1文字を無条件に落とす）で
 * 実データを壊した:
 *   "5か月" と "2か月" が両方 "か月" になり、別の選択肢が重複扱いされた
 *   "a, d" と "c, d" が両方 "d" になった
 * 選択肢本文は key と別に保存されているので、そもそも記号が付いているのは
 * 取り込み時の書き方の揺れだけ。落とし損ねるより、落としすぎない方を選ぶ。
 *
 * 落とすのは、記号だと確実に分かる形だけ:
 *   （ア） (a) (1) … 括弧で囲まれている
 *   ①②③        … 丸数字
 *   ア、 ア.      … かな1文字＋区切り記号（"アクセス" は区切りが続かないので対象外）
 */
const CHOICE_MARKER_PATTERN =
  /^\s*(?:[（(]\s*[アイウエオa-d1-9]\s*[）)]|[①-⑩]|[アイウエオ]\s*[.．、。:：)）])\s*/i;

/**
 * 出題の定型句。ほぼ全ての問題に現れるため、残すと「どの問題どうしも似ている」
 * という底上げが起き、閾値が意味を失う。内容を持たない言い回しだけを対象にする。
 *
 * 「どれか」のような短い語まで落とすと文が壊れるので、句として成立する形だけを消す。
 */
const BOILERPLATE_PATTERNS: RegExp[] = [
  /次の記述のうち/g,
  /次のうち/g,
  /次の[ａ-ｚa-z]{1,3}のうち/g,
  /最も適切なものはどれか/g,
  /最も適切なもの/g,
  /適切なものはどれか/g,
  /適切でないものはどれか/g,
  /正しいものはどれか/g,
  /誤っているものはどれか/g,
  /該当するものはどれか/g,
  /はどれか/g,
  /について、?/g,
  /に関する記述として/g,
  /として、?最も/g,
  /答えよ/g,
  /解答群/g,
  /ここで、/g,
];

/**
 * 落とす記号。句読点・括弧・引用符・空白といった「文の骨組み」だけを対象にする。
 *
 * 意味を持つ記号（- − + = / % $ # @ < > ~ ^ & _ |）は残す。
 * 落とすと "-15" と "15"、"50%" と "50" が同じ文字列になり、
 * 数値を答える選択肢どうしが重複判定されるため。
 *
 * ー（長音記号）だけは落とす。「コンピュータ / コンピューター」の表記ゆれを
 * 吸収するためで、これは意味の差ではない。
 */
const PUNCTUATION_PATTERN =
  /[\s　。、，．,.!?！？:：;；'"“”‘’`´()（）[\]［］{}｛｝「」『』【】〔〕《》〈〉・…‥ー]/g;

/** Unicode 正規化と大文字小文字の統一だけを行う（記号は残す）。 */
export function normalizeBase(text: string): string {
  return text.normalize("NFKC").toLowerCase();
}

/**
 * 類似度比較用の正規化。
 *
 * 手順（この順序が仕様）:
 *   1. Unicode NFKC（全角英数・半角カナ・互換文字を統一）
 *   2. 小文字化
 *   3. 選択肢記号の除去（先頭のみ）
 *   4. 定型句の除去
 *   5. 記号・空白・改行の除去
 */
export function normalizeForSimilarity(text: string): string {
  let out = normalizeBase(text);
  out = out.replace(CHOICE_MARKER_PATTERN, "");
  for (const pattern of BOILERPLATE_PATTERNS) {
    out = out.replace(pattern, "");
  }
  return out.replace(PUNCTUATION_PATTERN, "");
}

/**
 * 選択肢1件ぶんの正規化。先頭記号を確実に落としてから共通処理に渡す。
 * （"ア 100" と "100" を別物と数えないため）
 */
export function normalizeChoiceText(text: string): string {
  return normalizeForSimilarity(text);
}

/**
 * 「この2つは本当に同じ文字列か」を判定するための正規化。
 *
 * normalizeChoiceText との違いは、括弧も先頭記号も落とさないこと。落とすと、
 * 記号の位置だけが違う選択肢が同一に見えてしまう:
 *
 *   "j ← k ＋ (j － 10 × k)" と "j ← k ＋ (j － 10) × k"  … 括弧の位置が違う別の式
 *   "（1），（3）" と "（2），（3）"                       … 先頭の項番が違う別の組合せ
 *
 * どちらも「正答が一意に定まらない」という断定（blocker）の根拠にはできない。
 * 吸収するのは、全角半角・大文字小文字・空白と、文の区切りに使う句読点だけ。
 * 括弧や項番は構造を表す記号なので残す。
 */
const IDENTITY_PUNCTUATION_PATTERN = /[\s　。、，．,.]/g;

export function normalizeChoiceIdentity(text: string): string {
  return normalizeBase(text).replace(IDENTITY_PUNCTUATION_PATTERN, "");
}

/**
 * 問題全体（問題文＋選択肢）の正規化テキスト。
 *
 * 選択肢は key の順ではなく本文のソート順で連結する。選択肢の並べ替えだけを行った
 * 実質同一の問題を「別物」と判定させないため。
 */
export function normalizeQuestionText(
  prompt: string,
  choices: { key: string; text: string }[],
): string {
  const normalizedChoices = choices
    .map((c) => normalizeChoiceText(c.text))
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

  return [normalizeForSimilarity(prompt), ...normalizedChoices].join("");
}
